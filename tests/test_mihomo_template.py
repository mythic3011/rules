from __future__ import annotations

import unittest
import hashlib
import os

import yaml

from ai_profiles_test_support import load_generator
from ai_profiles.catalog import load_catalog
from ai_profiles.profile_languages import _is_yaml_comment
from ai_profiles.render.template import load_template, render_template
from ai_profiles.settings import TEMPLATE_DIR


MODULE = load_generator("generate_ai_profiles_template")


class MihomoTemplateTest(unittest.TestCase):
    def test_template_declares_only_renderer_owned_slots(self) -> None:
        template = load_template(TEMPLATE_DIR / "Custom_Clash_AI.yaml.tpl")
        expected = {
            "TITLE",
            "PROFILE_MARKER",
            "PROFILE_DESCRIPTION",
            "PROFILE_POLICY_NOTES",
            "GENERATOR_NOTE",
            "PORTS_SECTION",
            "PROXY_PROVIDERS_SECTION",
            "GEODATA_SECTION",
            "LOGGING_SECTION",
            "PROFILE_SECTION",
            "TUN_SECTION",
            "PROXY_GROUPS_SECTION",
            "RULES_SECTION",
            "RULE_PROVIDERS_SECTION",
            "PROVIDER_NOISE_EXCLUDE_PATTERN",
            "SECRET_LINES",
            "DNS_CONFIG",
            "PROXY_GROUPS",
            "RULES",
            "RULE_PROVIDERS",
        }
        actual = {
            token.split("}}", 1)[0]
            for token in template.split("{{")[1:]
        }
        self.assertEqual(actual, expected)

    def test_render_template_rejects_contract_mismatch(self) -> None:
        with self.assertRaisesRegex(RuntimeError, "missing=.*VALUE"):
            render_template("before {{VALUE}} after", {})
        with self.assertRaisesRegex(RuntimeError, "unexpected=.*EXTRA"):
            render_template("before {{VALUE}} after", {"VALUE": "ok", "EXTRA": "no"})

    def test_rendered_profiles_have_no_template_placeholders(self) -> None:
        for strict in (False, True):
            rendered = MODULE.render_yaml(strict=strict)
            self.assertNotIn("{{", rendered)
            self.assertNotIn("}}", rendered)
            for service in load_catalog().services:
                if "mihomo" in service.projections:
                    self.assertIn(f'name: "{service.group}"', rendered)
            self.assertIn('"jules.googleapis.com":', rendered)

    def test_explicit_language_changes_yaml_comments_only(self) -> None:
        for strict in (False, True):
            rendered = {language: MODULE.render_yaml(strict=strict, language=language) for language in ("en", "zh-Hant", "zh-Hans")}
            parsed = [yaml.safe_load(text) for text in rendered.values()]
            self.assertTrue(all(profile == parsed[0] for profile in parsed[1:]))
            comments = {language: "\n".join(line for line in text.splitlines() if line.lstrip().startswith("#")) for language, text in rendered.items()}
            self.assertEqual(len(set(comments.values())), 3)
            for language, text in rendered.items():
                self.assertIn({"en": "# Generated by Profile Builder.", "zh-Hant": "# 由 Profile Builder 產生。", "zh-Hans": "# 由 Profile Builder 生成。"}[language], text)
                self.assertNotRegex(comments[language], r"https?://|(?:token|password|credential)\s*[:=]")
                self.assertNotIn("Custom_OpenClash_Rules", comments[language])

    def test_default_yaml_bytes_remain_legacy_and_language_is_validated(self) -> None:
        if not os.environ.get("OPENCLASH_SECRET", "").strip():
            self.assertEqual(hashlib.sha256(MODULE.render_yaml(strict=False).encode()).hexdigest(), "25478bff2a6b66e12424481fe2e9599d7c6e17ea6aaed9e211743fd755521cb2")
            self.assertEqual(hashlib.sha256(MODULE.render_yaml(strict=True).encode()).hexdigest(), "7f7432ebdb0203ced08f241ccc5ab9d5f3fbc21cf5a52c31eae61bba7152f99e")
        with self.assertRaisesRegex(ValueError, "Unsupported profile language"):
            MODULE.render_yaml(strict=False, language="fr")

    def test_comment_catalog_rejects_unicode_line_breaks_and_c1_controls(self) -> None:
        for unsafe in ("# first\u0085second", "# first\u2028second", "# first\u2029second", "# bad\u0085"):
            self.assertFalse(_is_yaml_comment(unsafe))


if __name__ == "__main__":
    unittest.main()
